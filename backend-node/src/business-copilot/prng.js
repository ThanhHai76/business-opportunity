'use strict';

/** Deterministic PRNG so demo numbers (competitors, foot-traffic pattern...) never change between runs. */
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hashString(input) {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** A stable [0,1) number for a given key, independent of call order. */
function seededRandom(key) {
  return mulberry32(hashString(key))();
}

module.exports = { mulberry32, hashString, seededRandom };
